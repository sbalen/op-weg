function haversineKm(lat1, lng1, lat2, lng2) {
  const R = 6371
  const dLat = (lat2 - lat1) * (Math.PI / 180)
  const dLng = (lng2 - lng1) * (Math.PI / 180)
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLng / 2) ** 2
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
}

/**
 * Given a GPS position, return its km_marker along the Haarlem→Paris corridor.
 * Projects the point onto the nearest segment of the route polyline and sums
 * cumulative distance up to that projection.
 */
export function getKmMarker(userLat, userLng) {
  let bestDist = Infinity
  let bestKm = 0
  let cumKm = 0

  for (let i = 0; i < ROUTE.length - 1; i++) {
    const [lat1, lng1] = ROUTE[i]
    const [lat2, lng2] = ROUTE[i + 1]
    const segLen = haversineKm(lat1, lng1, lat2, lng2)

    // Project user position onto this segment (in lat/lng space)
    const dx = lat2 - lat1
    const dy = lng2 - lng1
    const len2 = dx * dx + dy * dy
    let t = len2 > 0
      ? ((userLat - lat1) * dx + (userLng - lng1) * dy) / len2
      : 0
    t = Math.max(0, Math.min(1, t))

    const projLat = lat1 + t * dx
    const projLng = lng1 + t * dy
    const dist = haversineKm(userLat, userLng, projLat, projLng)

    if (dist < bestDist) {
      bestDist = dist
      bestKm = cumKm + t * segLen
    }
    cumKm += segLen
  }

  return bestKm
}
